export type Lang = 'de' | 'en';
const TABLES: Record<Lang, Record<Key, string>> = { en, de };

// 'de' when the first preferred language is German, else 'en'
export const deviceLanguage = (): Lang => {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('de') ? 'de' : 'en';
  } catch {
    return 'en';
  }
};
export const isLang = (v: unknown): v is Lang => v === 'de' || v === 'en';

// Local settings of this device; `onboarded` is not synced, so a new phone shows the onboarding again
// owner: the e-mail of the account the people and profile on this device belong to
// ref: the inviter's profile slug from the first profile link (native only), sent once with the account's creation
type Settings = { language?: Lang; onboarded?: boolean; pushToken?: string | null; pushDone?: string | null; owner?: string | null; ref?: string };
export const readSettings = (): Settings => {
  const raw = readJson('settings') as Settings | null;
  return raw && typeof raw === 'object' ? raw : {};
};
export const writeSettings = (change: Settings) => writeJson('settings', { ...readSettings(), ...change });

let current: Lang = (() => {
  const saved = readSettings().language;
  return isLang(saved) ? saved : deviceLanguage();
})();
export const getLanguage = () => current;
// Changes the language for every following t() call; App re-renders the screens
export const setLanguage = (lang: Lang) => {
  current = lang;
  writeSettings({ language: lang });
};
export const locale = () => (current === 'de' ? 'de-DE' : 'en-GB');

export function t(key: Key, vars?: Record<string, string | number>): string {
  const text = TABLES[current][key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : text;
}
export const wishCount = (n: number) => (n === 1 ? t('wishOne') : t('wishMany', { n }));
